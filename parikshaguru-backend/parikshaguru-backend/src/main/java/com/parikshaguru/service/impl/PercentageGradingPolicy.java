@org.springframework.stereotype.Component
public class PercentageGradingPolicy implements GradingPolicy {
    @Override
    public String grade(double pct) {
        if (pct >= 90) return "A+";
        if (pct >= 80) return "A";
        if (pct >= 70) return "B+";
        if (pct >= 60) return "B";
        if (pct >= 50) return "C";
        if (pct >= 40) return "D";
        return "F";
    }
}
